// Generates CLAUDE.md, AGENTS.md and GEMINI.md from RULES.md + roles/*.md.
// Run from this folder (or the repository root): node sync-rules.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(here, p), 'utf8').trim();
const rules = read('RULES.md');

const targets = [
  { out: 'CLAUDE.md', role: 'roles/claude.md', tool: 'Claude Code' },
  { out: 'AGENTS.md', role: 'roles/codex.md', tool: 'Codex' },
  { out: 'GEMINI.md', role: 'roles/gemini.md', tool: 'Gemini CLI' },
];

for (const t of targets) {
  const header =
    `<!-- GENERATED for ${t.tool} from RULES.md + ${t.role} by sync-rules.mjs. ` +
    `Do not edit this file: edit the sources and run "node sync-rules.mjs". -->`;
  const body = `${header}\n\n${read(t.role)}\n\n${rules}\n`;
  writeFileSync(join(here, t.out), body);
  console.log(`wrote ${t.out}`);
}
